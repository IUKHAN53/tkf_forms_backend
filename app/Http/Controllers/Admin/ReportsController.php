/**
 * Reports hub.
 *
 * One place for every program report. The hub (index) lists the available
 * reports; each report has a filtered on-page view plus an Excel export. The
 * Fixed Site Report keeps its own controller (FixedSiteReportController) and is
 * surfaced here as one of the cards.
 *
 * All reports share the same filter vocabulary — date range (on submission
 * date), district and Union Council — resolved by resolveFilters() and applied
 * through applyFilters(). UC matching goes through the canonical variant list
 * (see ReportsSupport::ucVariants) so inconsistent spellings still aggregate.
 */
class ReportsController extends Controller
{
    use ReportsSupport;

    /* ===================================================================== *
     *  Hub
     * ===================================================================== */

    public function index()
    {
        return view('admin.reports.index', [
            'totals' => [
                'fgds_community'      => FgdsCommunity::count(),
                'fgds_health_workers' => FgdsHealthWorkers::count(),
                'bridging'            => BridgingTheGap::count(),
                'vaccination'         => VaccinationRecord::count(),
                'child_line_list'     => ChildLineList::count(),
            ],
        ]);
    }

    /* ===================================================================== *
     *  Program Summary
     * ===================================================================== */

    public function summary(Request $request)
    {
        $filters = $this->resolveFilters($request);

        return view('admin.reports.summary', array_merge(
            $this->filterOptions($filters),
            [
                'filters' => $filters,
                'report'  => $this->buildSummary($filters),
            ]
        ));
    }

    public function summaryExport(Request $request)
    {
        $filters = $this->resolveFilters($request);
        $data = $this->buildSummary($filters);
        $s = $data['summary'];

        $spreadsheet = $this->newReportSpreadsheet('Program Summary Report', $this->filterSubject($filters));
        $i = 0;

        $this->writeSheet($spreadsheet, $i++, 'Summary', ['Field', 'Value'], [
            ['Report', 'Program Summary Report'],
            ['District', $filters['district'] ?: 'All districts'],
            ['Union Council', $filters['uc'] ?: 'All union councils'],
            ['Date from', $filters['from'] ?: '—'],
            ['Date to', $filters['to'] ?: '—'],
            ['Generated at', now()->format('M d, Y H:i')],
            ['Generated by', auth()->user()->name ?? 'Admin'],
            ['', ''],
            ['FGDs-Community sessions', $s['fgds_community']],
            ['FGDs-Community participants', $s['fgds_community_participants']],
            ['FGDs-Community barriers', $s['fgds_community_barriers']],
            ['FGDs-Health Workers sessions', $s['fgds_health_workers']],
            ['FGDs-Health Workers participants', $s['fgds_health_workers_participants']],
            ['FGDs-Health Workers barriers', $s['fgds_health_workers_barriers']],
            ['Bridging the Gap sessions', $s['bridging']],
            ['Bridging the Gap action plans', $s['action_plans']],
            ['Bridging the Gap IIT members', $s['iit_members']],
            ['Vaccination records', $s['vaccination']],
            ['Vaccination records (vaccinated)', $s['vaccinated']],
            ['Child line list children', $s['child_line_list']],
            ['Child line list (zero dose)', $s['zero_dose']],
            ['Child line list (defaulter)', $s['defaulter']],
        ]);

        $this->writeSheet($spreadsheet, $i++, 'By Union Council',
            ['Union Council', 'FGD-Community', 'FGD-Health Workers', 'Bridging the Gap', 'Vaccination', 'Child Line List'],
            collect($data['by_uc'])->map(fn ($r) => [
                $r['uc'], $r['fgds_community'], $r['fgds_health_workers'], $r['bridging'], $r['vaccination'], $r['child_line_list'],
            ])->all(),
            'No records for the selected filters.');

        $this->writeSheet($spreadsheet, $i++, 'Barriers by Category',
            ['Category', 'Community', 'Health Workers', 'Total'],
            collect($data['barriers_by_category'])->map(fn ($r) => [
                $r['name'], $r['community'], $r['health_workers'], $r['total'],
            ])->all());

        $filename = 'program-summary_' . date('Y-m-d') . '.xlsx';

        return $this->streamWorkbook($spreadsheet, $filename);
    }

    /* ===================================================================== *
     *  Barriers
     * ===================================================================== */

    public function barriers(Request $request)
    {
        $filters = $this->resolveFilters($request);
        $scope = $this->resolveScope($request);

        return view('admin.reports.barriers', array_merge(
            $this->filterOptions($filters),
            [
                'filters' => $filters,
                'scope'   => $scope,
                'report'  => $this->buildBarriers($filters, $scope),
            ]
        ));
    }

    public function barriersExport(Request $request)
    {
        $filters = $this->resolveFilters($request);
        $scope = $this->resolveScope($request);
        $data = $this->buildBarriers($filters, $scope);

        $spreadsheet = $this->newReportSpreadsheet('Barriers Report', $this->filterSubject($filters));
        $i = 0;

        $this->writeSheet($spreadsheet, $i++, 'By Category',
            ['Category', 'Community', 'Health Workers', 'Total'],
            collect($data['by_category'])->map(fn ($r) => [
                $r['name'], $r['community'], $r['health_workers'], $r['total'],
            ])->all());

        $this->writeSheet($spreadsheet, $i++, 'Barrier Details',
            ['Source', 'Form ID', 'Date', 'UC', 'Location', 'Category', 'Sr. No', 'Barrier'],
            collect($data['details'])->map(fn ($r) => [
                $r['source'], $r['form_id'], $r['date'], $r['uc'], $r['location'], $r['category'], $r['serial'], $r['text'],
            ])->all(),
            'No barriers for the selected filters.');

        $filename = 'barriers-report_' . date('Y-m-d') . '.xlsx';

        return $this->streamWorkbook($spreadsheet, $filename);
    }

    /* ===================================================================== *
     *  Vaccination Coverage
     * ===================================================================== */

