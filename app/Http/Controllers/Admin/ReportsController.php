    /* ===================================================================== *
     *  Report builders
     * ===================================================================== */

    private function buildSummary(array $f): array
    {
        $fc = $this->applyFilters(FgdsCommunity::query(), $f)->withCount(['participants', 'barriers'])->get();
        $fh = $this->applyFilters(FgdsHealthWorkers::query(), $f, hasDistrict: false)->withCount(['participants', 'barriers'])->get();
        $btg = $this->applyFilters(BridgingTheGap::query(), $f)->withCount(['participants', 'teamMembers', 'actionPlans'])->get();
        $vac = $this->applyFilters(VaccinationRecord::query(), $f)->get(['id', 'uc', 'vaccinated', 'category']);
        $cll = $this->applyFilters(ChildLineList::query(), $f)->get(['id', 'uc', 'type']);

        return [
            'summary' => [
                'fgds_community'                   => $fc->count(),
                'fgds_community_participants'      => $fc->sum('participants_count'),
                'fgds_community_barriers'          => $fc->sum('barriers_count'),
                'fgds_health_workers'              => $fh->count(),
                'fgds_health_workers_participants' => $fh->sum('participants_count'),
                'fgds_health_workers_barriers'     => $fh->sum('barriers_count'),
                'bridging'                         => $btg->count(),
                'bridging_participants'            => $btg->sum('participants_count'),
                'action_plans'                     => $btg->sum('action_plans_count'),
                'iit_members'                      => $btg->sum('team_members_count'),
                'vaccination'                      => $vac->count(),
                'vaccinated'                       => $vac->where('vaccinated', 'YES')->count(),
                'child_line_list'                  => $cll->count(),
                'zero_dose'                        => $cll->filter(fn ($r) => Str::contains(Str::lower((string) $r->type), 'zero'))->count(),
                'defaulter'                        => $cll->filter(fn ($r) => Str::contains(Str::lower((string) $r->type), 'default'))->count(),
            ],
            'by_uc'                => $this->tallyByUc($fc, $fh, $btg, $vac, $cll),
            'barriers_by_category' => $this->barrierCategoryTotals($fc->pluck('id'), $fh->pluck('id')),
        ];
    }

    private function buildBarriers(array $f, string $scope): array
    {
        $wantCommunity = $scope === 'both' || $scope === 'community';
        $wantHealth = $scope === 'both' || $scope === 'health_workers';

        $community = $wantCommunity
            ? $this->applyFilters(FgdsCommunity::query(), $f)->with('barriers.category')->get()
            : collect();
        $health = $wantHealth
            ? $this->applyFilters(FgdsHealthWorkers::query(), $f, hasDistrict: false)->with('barriers.category')->get()
            : collect();

        // Category totals seeded from the canonical list so every category shows.
        $categories = [];
        foreach (BarrierCategory::CANONICAL as $name) {
            $categories[$name] = ['name' => $name, 'community' => 0, 'health_workers' => 0, 'total' => 0];
        }
        $uncategorized = ['name' => 'Uncategorized', 'community' => 0, 'health_workers' => 0, 'total' => 0];

        $details = [];

        foreach ($community as $r) {
            foreach ($r->barriers as $b) {
                $cat = $b->category->name ?? null;
                $bucket = $cat && isset($categories[$cat]) ? $categories[$cat] : $uncategorized;
                $bucket['community']++;
                $bucket['total']++;
                if ($cat && isset($categories[$cat])) { $categories[$cat] = $bucket; } else { $uncategorized = $bucket; }
                $details[] = [
                    'source' => 'Community', 'form_id' => $r->unique_id,
                    'date' => optional($r->date)->format('Y-m-d'), 'uc' => $r->uc,
                    'location' => $r->venue, 'category' => $cat ?? 'Uncategorized',
                    'serial' => $b->serial_number, 'text' => $b->barrier_text,
                ];
            }
        }

        foreach ($health as $r) {
            foreach ($r->barriers as $b) {
                $cat = $b->category->name ?? null;
                $bucket = $cat && isset($categories[$cat]) ? $categories[$cat] : $uncategorized;
                $bucket['health_workers']++;
                $bucket['total']++;
                if ($cat && isset($categories[$cat])) { $categories[$cat] = $bucket; } else { $uncategorized = $bucket; }
                $details[] = [
                    'source' => 'Health Workers', 'form_id' => $r->unique_id,
                    'date' => optional($r->date)->format('Y-m-d'), 'uc' => $r->uc,
                    'location' => $r->hfs, 'category' => $cat ?? 'Uncategorized',
                    'serial' => $b->serial_number, 'text' => $b->barrier_text,
                ];
            }
        }

        $byCategory = collect($categories)->values();
        if ($uncategorized['total'] > 0) {
            $byCategory->push($uncategorized);
        }
        // Sort most-frequent first, but keep zero-rows in canonical order at the end.
        $byCategory = $byCategory->sortByDesc('total')->values();

        return [
            'by_category' => $byCategory->all(),
            'details'     => $details,
            'totals'      => [
                'sessions'  => $community->count() + $health->count(),
                'community' => $community->count(),
                'health'    => $health->count(),
                'barriers'  => $byCategory->sum('total'),
            ],
        ];
    }

    private function buildVaccination(array $f, string $category, string $vaccinated): array
    {
        $query = $this->applyFilters(VaccinationRecord::query(), $f);
        if ($f['fix_site'] !== '') {
            $query->where('fix_site', $f['fix_site']);
        }
        if ($category !== '') {
            $query->where('category', $category);
        }
        if ($vaccinated !== '') {
            $query->where('vaccinated', $vaccinated);
        }

        $records = $query->with('user')->orderByDesc('created_at')->get();

        $total = $records->count();
        $vac = $records->where('vaccinated', 'YES')->count();
        $notVac = $total - $vac;

        $cats = [];
        foreach (['Defaulter', 'Refusal', 'Zero Dose'] as $c) {
            $rows = $records->where('category', $c);
            $t = $rows->count();
            $v = $rows->where('vaccinated', 'YES')->count();
            $cats[] = [
                'category'       => $c,
                'total'          => $t,
                'vaccinated'     => $v,
                'not_vaccinated' => $t - $v,
                'coverage'       => $t > 0 ? round($v / $t * 100, 1) : 0,
            ];
        }

        return [
            'summary' => [
                'total'          => $total,
                'vaccinated'     => $vac,
                'not_vaccinated' => $notVac,
                'coverage'       => $total > 0 ? round($vac / $total * 100, 1) : 0,
            ],
            'by_category' => $cats,
            'by_uc'       => $this->vaccinationByUc($records),
            'records'     => $records,
        ];
    }

    /* ===================================================================== *
     *  Aggregation helpers
     * ===================================================================== */

    /** Count sessions per consolidated Union Council across all form types. */
    private function tallyByUc($fc, $fh, $btg, $vac, $cll): array
    {
        $rows = [];
        $add = function (string $key, $collection) use (&$rows) {
            foreach ($collection as $item) {
                $uc = DashboardController::getConsolidatedUcName($item->uc) ?: ($item->uc ?: 'Unknown');
                $rows[$uc] ??= ['uc' => $uc, 'fgds_community' => 0, 'fgds_health_workers' => 0, 'bridging' => 0, 'vaccination' => 0, 'child_line_list' => 0];
                $rows[$uc][$key]++;
            }
        };
        $add('fgds_community', $fc);
        $add('fgds_health_workers', $fh);
        $add('bridging', $btg);
        $add('vaccination', $vac);
        $add('child_line_list', $cll);

        ksort($rows, SORT_NATURAL | SORT_FLAG_CASE);

        return array_values($rows);
    }

    private function vaccinationByUc($records): array
    {
        $rows = [];
        foreach ($records as $r) {
            $uc = DashboardController::getConsolidatedUcName($r->uc) ?: ($r->uc ?: 'Unknown');
            $rows[$uc] ??= ['uc' => $uc, 'total' => 0, 'vaccinated' => 0];
            $rows[$uc]['total']++;
            if ($r->vaccinated === 'YES') {
                $rows[$uc]['vaccinated']++;
            }
        }
        ksort($rows, SORT_NATURAL | SORT_FLAG_CASE);

        return array_values($rows);
    }

    /** Barrier counts per canonical category for the given FGD record ids. */
    private function barrierCategoryTotals($communityIds, $healthIds): array
    {
        $categories = [];
        foreach (BarrierCategory::CANONICAL as $name) {
            $categories[$name] = ['name' => $name, 'community' => 0, 'health_workers' => 0, 'total' => 0];
        }
        $uncategorized = ['name' => 'Uncategorized', 'community' => 0, 'health_workers' => 0, 'total' => 0];

        $tally = function ($rows, string $key) use (&$categories, &$uncategorized) {
            foreach ($rows as $row) {
                $name = $row->name ?? null;
                if ($name && isset($categories[$name])) {
                    $categories[$name][$key] += $row->c;
                    $categories[$name]['total'] += $row->c;
                } else {
                    $uncategorized[$key] += $row->c;
                    $uncategorized['total'] += $row->c;
                }
            }
        };

        if ($communityIds->isNotEmpty()) {
            $tally(\App\Models\FgdsCommunityBarrier::query()
                ->whereIn('fgds_community_id', $communityIds)
                ->leftJoin('barrier_categories', 'fgds_community_barriers.barrier_category_id', '=', 'barrier_categories.id')
                ->selectRaw('barrier_categories.name as name, count(*) as c')
                ->groupBy('barrier_categories.name')
                ->get(), 'community');
        }
        if ($healthIds->isNotEmpty()) {
            $tally(\App\Models\FgdsHealthWorkersBarrier::query()
                ->whereIn('fgds_health_workers_id', $healthIds)
                ->leftJoin('barrier_categories', 'fgds_health_workers_barriers.barrier_category_id', '=', 'barrier_categories.id')
                ->selectRaw('barrier_categories.name as name, count(*) as c')
                ->groupBy('barrier_categories.name')
                ->get(), 'health_workers');
        }

        $out = collect($categories)->values();
        if ($uncategorized['total'] > 0) {
            $out->push($uncategorized);
        }

        return $out->sortByDesc('total')->values()->all();
    }

    /* ===================================================================== *
     *  Filters
     * ===================================================================== */

    private function resolveFilters(Request $request): array
    {
        return [
            'from'      => $this->validDate($request->query('from')),
            'to'        => $this->validDate($request->query('to')),
            'district'  => trim((string) $request->query('district', '')),
            'uc'        => trim((string) $request->query('uc', '')),
            'fix_site'  => trim((string) $request->query('fix_site', '')),
        ];
    }

    private function resolveScope(Request $request): string
    {
        $scope = trim((string) $request->query('scope', 'both'));

        return in_array($scope, ['both', 'community', 'health_workers'], true) ? $scope : 'both';
    }

    /**
     * Apply the shared date/district/UC filters to a query. `hasDistrict` is
     * false for FGDs-Health-Workers, which has no district column.
     */
    private function applyFilters(Builder $query, array $f, bool $hasDistrict = true): Builder
    {
        if ($f['from']) {
            $query->whereDate('created_at', '>=', $f['from']);
        }
        if ($f['to']) {
            $query->whereDate('created_at', '<=', $f['to']);
        }
        if ($f['district'] !== '' && $hasDistrict) {
            $query->where('district', $f['district']);
        }
        if ($f['uc'] !== '') {
            $query->whereIn('uc', $this->ucVariants($f['uc']));
        }

        return $query;
    }

    private function validDate($value): ?string
    {
        $value = trim((string) $value);
        if ($value === '') {
            return null;
        }
        try {
            return CarbonImmutable::parse($value)->toDateString();
        } catch (\Throwable) {
            return null;
        }
    }

    /** Dropdown options for the filter bar; fix-site list depends on chosen UC. */
    private function filterOptions(array $filters): array
    {
        return [
            'districts'     => $this->districts(),
            'unionCouncils' => $this->unionCouncils(),
            'fixSites'      => $filters['uc'] !== '' ? $this->fixSitesForUc($filters['uc']) : collect(),
        ];
    }

    private function filterSubject(array $f): string
    {
        $parts = array_filter([
            $f['district'] ?: null,
            $f['uc'] ?: null,
            $f['from'] || $f['to'] ? trim(($f['from'] ?: '…') . ' to ' . ($f['to'] ?: '…')) : null,
        ]);

        return $parts ? implode(' / ', $parts) : 'All records';
    }
}
